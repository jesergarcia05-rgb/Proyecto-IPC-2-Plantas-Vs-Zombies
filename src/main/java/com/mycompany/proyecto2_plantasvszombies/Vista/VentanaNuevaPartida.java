         private void seleccionarArchivoJSON() {

    javax.swing.UIManager.put(
            "FileChooser.openButtonText",
            "Seleccionar"
    );

    javax.swing.UIManager.put(
            "FileChooser.cancelButtonText",
            "Cancelar"
    );

    javax.swing.UIManager.put(
            "FileChooser.lookInLabelText",
            "Buscar en:"
    );

    javax.swing.UIManager.put(
            "FileChooser.fileNameLabelText",
            "Nombre:"
    );

    javax.swing.UIManager.put(
            "FileChooser.filesOfTypeLabelText",
            "Tipo de archivo:"
    );

    JFileChooser selector = new JFileChooser();

    selector.setDialogTitle("Seleccionar nivel");

    FileNameExtensionFilter filtro =
            new FileNameExtensionFilter(
                    "Archivos JSON (*.json)",
                    "json"
            );

    selector.setFileFilter(filtro);

    int resultado = selector.showOpenDialog(this);

    if (resultado == JFileChooser.APPROVE_OPTION) {

        archivoNivelSeleccionado =
                selector.getSelectedFile();

        JOptionPane.showMessageDialog(
                this,
                "Archivo seleccionado:\n"
                + archivoNivelSeleccionado.getName()
        );
    }
}
private void iniciarPartida() {

    if (archivoNivelSeleccionado == null) {

        JOptionPane.showMessageDialog(
                this,
                "Debe seleccionar un archivo JSON."
        );

        return;
    }

    String dificultad =
            jComboBox1.getSelectedItem().toString();

    try {

        LectorNivel lector =
                new LectorNivel();

        ConfiguracionNivel configuracion =
                lector.leerNivel(
                        archivoNivelSeleccionado
                );

        Jardin jardin =
                new Jardin(
                        configuracion.getJardin()
                );

        VentanaPartida ventana =
                new VentanaPartida(
                        cuentaActiva,
                        configuracion,
                        jardin,
                        dificultad
                );

        ventana.setVisible(true);

        this.dispose();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Archivo de nivel inválido."
                + "\n"
                + e.getMessage()
        );
    }
}

