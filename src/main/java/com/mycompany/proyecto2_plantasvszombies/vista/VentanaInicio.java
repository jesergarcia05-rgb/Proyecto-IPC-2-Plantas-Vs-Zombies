 private void configurarTeclado() {

    javax.swing.InputMap inputMap =
            getRootPane().getInputMap(
                    javax.swing.JComponent.WHEN_IN_FOCUSED_WINDOW);

    javax.swing.ActionMap actionMap =
            getRootPane().getActionMap();

    inputMap.put(
            javax.swing.KeyStroke.getKeyStroke(
                    java.awt.event.KeyEvent.VK_LEFT, 0),
            "izquierda");

    actionMap.put(
            "izquierda",
            new javax.swing.AbstractAction() {
                public void actionPerformed(
                        java.awt.event.ActionEvent e) {

                    jButton1.requestFocusInWindow();
                }
            });

    inputMap.put(
            javax.swing.KeyStroke.getKeyStroke(
                    java.awt.event.KeyEvent.VK_RIGHT, 0),
            "derecha");

    actionMap.put(
            "derecha",
            new javax.swing.AbstractAction() {
                public void actionPerformed(
                        java.awt.event.ActionEvent e) {

                    jButton2.requestFocusInWindow();
                }
            });

    inputMap.put(
            javax.swing.KeyStroke.getKeyStroke(
                    java.awt.event.KeyEvent.VK_ENTER, 0),
            "enter");

    actionMap.put(
            "enter",
            new javax.swing.AbstractAction() {
                public void actionPerformed(
                        java.awt.event.ActionEvent e) {

                    if (jButton1.hasFocus()) {
                        jButton1.doClick();
                    } else if (jButton2.hasFocus()) {
                        jButton2.doClick();
                    }
                }
            });
}
private void cargarFondo() {
    java.net.URL ruta = getClass().getResource("/Imagenes/Fondo.jpg");

    if (ruta != null) {
        jLabel2.setIcon(new javax.swing.ImageIcon(ruta));
    }
}
